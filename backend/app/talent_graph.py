def score_person(person: dict[str, Any], parsed_jd: dict[str, Any]) -> float:
    score = 10.0
    blob = " ".join(
        [
            person.get("headline", ""),
            person.get("location", ""),
            " ".join(person.get("skills") or []),
        ]
    ).lower()
    title = (parsed_jd.get("title_guess") or "").lower()
    if title and title in blob:
        score += 40
    for skill in parsed_jd.get("skills") or []:
        if skill.lower() in blob:
            score += 8
    loc = (parsed_jd.get("location_guess") or "").lower()
    if loc and loc in (person.get("location") or "").lower():
        score += 20
    for lang in parsed_jd.get("languages") or []:
        if lang.lower() in blob:
            score += 5
    for keyword in (parsed_jd.get("keywords") or [])[:12]:
        if keyword.lower() in blob:
            score += 1.5
    return round(min(score, 99), 1)
